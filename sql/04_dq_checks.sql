-- Data-quality checks. The Python runner sets: SET pulse.run_id = '<epoch seconds>'.
-- severity: error = analysis can be wrong if ignored; warn = investigate; info = a fact to document.

INSERT INTO ops.dq_log (run_id, check_name, severity, failing_rows, total_rows)
SELECT current_setting('pulse.run_id')::bigint, v.check_name, v.severity, v.failing_rows, v.total_rows
FROM (VALUES
 ('duplicate_order_ids', 'error',
    (SELECT COUNT(*) - COUNT(DISTINCT order_id) FROM staging.orders),
    (SELECT COUNT(*) FROM staging.orders)),
 ('orders_missing_purchase_ts', 'error',
    (SELECT COUNT(*) FROM staging.orders WHERE purchase_ts IS NULL),
    (SELECT COUNT(*) FROM staging.orders)),
 ('delivered_status_without_delivery_ts', 'warn',
    (SELECT COUNT(*) FROM staging.orders WHERE order_status = 'delivered' AND delivered_ts IS NULL),
    (SELECT COUNT(*) FROM staging.orders WHERE order_status = 'delivered')),
 ('delivery_ts_but_status_not_delivered', 'warn',
    (SELECT COUNT(*) FROM staging.orders WHERE delivered_ts IS NOT NULL AND order_status <> 'delivered'),
    (SELECT COUNT(*) FROM staging.orders WHERE delivered_ts IS NOT NULL)),
 ('delivered_before_purchase', 'error',
    (SELECT COUNT(*) FROM staging.orders WHERE delivered_ts < purchase_ts),
    (SELECT COUNT(*) FROM staging.orders WHERE delivered_ts IS NOT NULL)),
 ('carrier_handoff_before_approval', 'warn',
    (SELECT COUNT(*) FROM staging.orders WHERE carrier_ts < approved_ts),
    (SELECT COUNT(*) FROM staging.orders WHERE carrier_ts IS NOT NULL)),
 ('items_orphan_orders', 'error',
    (SELECT COUNT(*) FROM staging.order_items i WHERE NOT EXISTS (SELECT 1 FROM staging.orders o WHERE o.order_id = i.order_id)),
    (SELECT COUNT(*) FROM staging.order_items)),
 ('orders_without_items', 'warn',
    (SELECT COUNT(*) FROM staging.orders o WHERE NOT EXISTS (SELECT 1 FROM staging.order_items i WHERE i.order_id = o.order_id)),
    (SELECT COUNT(*) FROM staging.orders)),
 ('items_orphan_sellers', 'error',
    (SELECT COUNT(*) FROM staging.order_items i WHERE NOT EXISTS (SELECT 1 FROM staging.sellers s WHERE s.seller_id = i.seller_id)),
    (SELECT COUNT(*) FROM staging.order_items)),
 ('items_orphan_products', 'warn',
    (SELECT COUNT(*) FROM staging.order_items i WHERE NOT EXISTS (SELECT 1 FROM staging.products p WHERE p.product_id = i.product_id)),
    (SELECT COUNT(*) FROM staging.order_items)),
 ('payments_orphan_orders', 'error',
    (SELECT COUNT(*) FROM staging.payments p WHERE NOT EXISTS (SELECT 1 FROM staging.orders o WHERE o.order_id = p.order_id)),
    (SELECT COUNT(*) FROM staging.payments)),
 ('payments_zero_or_negative_value', 'warn',
    (SELECT COUNT(*) FROM staging.payments WHERE payment_value <= 0),
    (SELECT COUNT(*) FROM staging.payments)),
 ('review_rows_dropped_by_dedupe', 'info',
    (SELECT (SELECT COUNT(*) FROM raw.order_reviews) - (SELECT COUNT(*) FROM staging.reviews)),
    (SELECT COUNT(*) FROM raw.order_reviews)),
 ('review_score_out_of_range', 'error',
    (SELECT COUNT(*) FROM staging.reviews WHERE review_score NOT BETWEEN 1 AND 5),
    (SELECT COUNT(*) FROM staging.reviews)),
 ('products_missing_category', 'warn',
    (SELECT COUNT(*) FROM staging.products WHERE category_pt IS NULL),
    (SELECT COUNT(*) FROM staging.products)),
 ('product_categories_without_translation', 'warn',
    (SELECT COUNT(*) FROM staging.products p WHERE p.category_pt IS NOT NULL
        AND NOT EXISTS (SELECT 1 FROM staging.category_translation t WHERE t.category_pt = p.category_pt)),
    (SELECT COUNT(*) FROM staging.products WHERE category_pt IS NOT NULL)),
 ('customers_without_geo', 'warn',
    (SELECT COUNT(*) FROM dw.dim_customer c WHERE NOT EXISTS (SELECT 1 FROM dw.dim_geo g WHERE g.zip_prefix = c.zip_prefix)),
    (SELECT COUNT(*) FROM dw.dim_customer)),
 ('sellers_without_geo', 'warn',
    (SELECT COUNT(*) FROM dw.dim_seller s WHERE NOT EXISTS (SELECT 1 FROM dw.dim_geo g WHERE g.zip_prefix = s.zip_prefix)),
    (SELECT COUNT(*) FROM dw.dim_seller)),
 ('multi_seller_orders_excluded_from_seller_metrics', 'info',
    (SELECT COUNT(*) FROM dw.fact_orders WHERE n_sellers > 1),
    (SELECT COUNT(*) FROM dw.fact_orders WHERE n_sellers >= 1))
) AS v(check_name, severity, failing_rows, total_rows);
